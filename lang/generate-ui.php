    $locales[$locale] = array_merge($locales[$locale] ?? [], $map);
}

function export_php(array $data): string
{
    $out = "<?php\n\nreturn [\n";
    foreach ($data as $key => $value) {
        $out .= '    '.var_export($key, true).' => '.var_export($value, true).",\n";
    }

    return $out."];\n";
}

foreach ($locales as $locale => $map) {
    $merged = [];
    foreach ($en as $key => $english) {
        $merged[$key] = $map[$key] ?? $english;
    }
    $dir = __DIR__.'/'.$locale;
    if (! is_dir($dir)) {
        mkdir($dir, 0775, true);
    }
    file_put_contents($dir.'/ui.php', export_php($merged));
    echo "Wrote lang/{$locale}/ui.php\n";
}
